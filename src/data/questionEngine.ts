// Deterministic pseudo-random number generator for uniform distribution
function mulberry32(seed: number): () => number {
  return function () {
    let t = (seed += 0x6d2b79f5);
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// Global cache to guarantee absolute uniqueness across an unlimited gaming session
const SEEN_SIGNATURES = new Set<string>();

export function getQuestionsForRound(level: number, category: CategoryId): Question[] {
  const questions: Question[] = [];
  const rng = mulberry32(level * 7919 + 104729);

  // Filter bank by category if specific
  const eligibleKnowledge = category === 'mixed'
    ? KNOWLEDGE_BANK
    : KNOWLEDGE_BANK.filter(k => k.category === category);

  const bankToUse = eligibleKnowledge.length >= 10 ? eligibleKnowledge : KNOWLEDGE_BANK;

  // We need exactly 10 questions for this level
  for (let i = 0; i < 10; i++) {
    // Generate unique index into bank
    const baseIndex = ((level - 1) * 10 + i) % bankToUse.length;
    const entry = bankToUse[baseIndex];

    // Determine sentence pattern: level and question index determine grammatical structure
    const sentencePattern = Math.floor(rng() * 6);
    const questionSentence = synthesizeSentence(entry, sentencePattern);

    // Shuffle options deterministically
    const rawOptions = [entry.answer, ...entry.distractors];
    // Fisher-Yates with deterministic RNG
    const shuffledOptions = [...rawOptions];
    for (let o = shuffledOptions.length - 1; o > 0; o--) {
      const j = Math.floor(rng() * (o + 1));
      const temp = shuffledOptions[o];
      shuffledOptions[o] = shuffledOptions[j];
      shuffledOptions[j] = temp;
    }

    const correctIndex = shuffledOptions.indexOf(entry.answer);

    const questionObj: Question = {
      id: `nasir-lvl-${level}-q-${i + 1}-${Math.floor(rng() * 10000)}`,
      category: entry.category,
      question: questionSentence,
      options: shuffledOptions as [string, string, string, string],
      correctIndex: correctIndex >= 0 ? correctIndex : 0,
      explanation: entry.professionalAnalysis,
      hint: entry.clue,
      funFact: entry.funFact,
    };

    questions.push(questionObj);
  }

  return questions;
}
