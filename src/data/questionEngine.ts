// DYNAMIC LINGUISTIC SENTENCE DIVERSIFIER (৬টি বিভিন্ন ধাঁচের বাক্য কাঠামো)
// -------------------------------------------------------------

function synthesizeSentence(entry: KnowledgeEntry, sentencePattern: number): string {
  switch (sentencePattern % 6) {
    case 0:
      // সরাসরি প্রামাণ্য জিজ্ঞাসা
      return `জ্ঞানকোষ থেকে প্রশ্ন: ${entry.subject} নিচের কোনটি?`;
    case 1:
      // বৈশিষ্ট্যভিত্তিক শনাক্তকরণ
      return `নিচের কোন বিকল্পটি "${entry.subject}" হিসেবে ঐতিহাসিকভাবে স্বীকৃত ও সঠিক?`;
    case 2:
      // শিক্ষণীয় তথ্যভিত্তিক বাক্য
      return `প্রামাণ্য তথ্য ও সাধারণ জ্ঞানের বিচারে, ${entry.subject} হলো—`;
    case 3:
      // ক্লু বা ইঙ্গিত সমৃদ্ধ শনাক্তকরণ
      return `ক্লু: "${entry.clue}"— এই বর্ণনার আলোকে ${entry.subject} কোনটি?`;
    case 4:
      // অনুসন্ধানমূলক বিশ্লেষণ
      return `সঠিক বিকল্পটি নির্বাচন করো: নিচের কোনটি ${entry.subject}?`;
    case 5:
    default:
      // প্রাতিষ্ঠানিক ও শিক্ষামূলক উপস্থাপনা
      return `শিক্ষণীয় জিজ্ঞাসা: ${entry.subject} সম্পর্কিত সঠিক উত্তরটি বেছে নাও—`;
  }
}

